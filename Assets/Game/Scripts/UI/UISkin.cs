using UnityEngine;

namespace BallSortGame.UI
{
    /// <summary>
    /// Sprites of the Art/UI/NewUI kit, gathered in Resources/UISkin.asset so UI built in code at runtime (Jump Path)
    /// can use them. Created and filled by the editor menu BallSort > Apply New UI.
    /// </summary>
    [CreateAssetMenu(menuName = "BallSort/UI Skin", fileName = "UISkin")]
    public class UISkin : ScriptableObject
    {
        public const string ResourcePath = "UISkin";

        [Header("Buttons and frames")]
        public Sprite buttonCircle;
        public Sprite buttonSquare;
        public Sprite buttonRect;
        public Sprite buttonRectGreen;
        public Sprite buttonRectRed;
        public Sprite circleFrame;
        public Sprite squareFrame;
        public Sprite greenCircle;
        public Sprite redCircle;
        [Tooltip("Gold-framed stadium button (Button elipse): CONTINUE / home / try again, the LEVEL pill, prices and the coin balance.")]
        public Sprite buttonPill;

        [Header("Popups")]
        [Tooltip("Big gold-framed panel (Big pop up shaded): WELL DONE, OUT OF MOVES, the Mana Flip grid.")]
        public Sprite popupPanel;
        [Tooltip("Small gold-framed panel (Small pop up shaded): booster bar, Mana Flip rewards.")]
        public Sprite pill;
        [Tooltip("Flat pink panel without a frame (small pop up FLAT shade): the booster info panel.")]
        public Sprite panelFlat;
        [Tooltip("Full-screen dim behind popups.")]
        public Sprite overlay;

        [Header("Settings page")]
        [Tooltip("Gold-framed settings panel (Settings background).")]
        public Sprite settingsBackground;
        [Tooltip("Full-screen flat pink (FLAT pink background for settings); kept for a frameless layout.")]
        public Sprite settingsBackgroundFlat;
        [Tooltip("Striped level bar under each settings button.")]
        public Sprite settingsBar;

        [Header("Rewards")]
        public Sprite rewardStar;
        public Sprite rewardPotion;
        public Sprite rewardCrystal;
        [Tooltip("Seed / plant reward of the Mana Garden.")]
        public Sprite rewardSeed;

        [Header("Mana Flip")]
        [Tooltip("Flat strip behind each reward row.")]
        public Sprite rewardRow;
        [Tooltip("Pink glow drawn behind a found reward on its card.")]
        public Sprite rewardGlow;
        [Tooltip("Dark tile shown under a revealed reward.")]
        public Sprite cardBackFound;

        [Header("Items")]
        public Sprite coin;
        public Sprite heart;
        public Sprite brokenHeart;
        public Sprite logo;
        public Sprite logoFull;

        [Header("Main menu")]
        public Sprite background;
        public Sprite sparkle;

        [Header("Icons")]
        public Sprite iconClose;
        public Sprite iconHome;
        public Sprite iconSettings;
        public Sprite iconRestart;
        public Sprite iconUndo;
        public Sprite iconShuffle;
        public Sprite iconAddTube;
        [Tooltip("Little-tube booster: a short version of the add-tube icon (generated by Apply New UI).")]
        public Sprite iconAddSmallTube;
        public Sprite iconSound;
        public Sprite iconMusic;
        public Sprite iconHaptic;
        public Sprite iconCheck;
        [Tooltip("Arrow (points up) drawn under one-way tubes; flipped for in-only tubes.")]
        public Sprite iconArrow;
        [Tooltip("Sprout icon of the Mana Garden button.")]
        public Sprite iconPlant;

        [Header("Lettering (Art/Fonts)")]
        [Tooltip("A TTF/OTF dropped into Art/Fonts; every Text uses it when set (Art/Fonts ships word pictures only).")]
        public Font font;
        [Tooltip("Word pictures of the mockup, drawn in place of the matching labels (WordArt.Picture).")]
        public Sprite wordLevel;
        public Sprite wordContinue;
        public Sprite wordHome;
        public Sprite wordTryAgain;
        public Sprite wordWellDone;
        public Sprite wordOutOfMoves;
        public Sprite wordManaFlip;
        public Sprite wordManaGarden;
        [Tooltip("Digit pictures 0-9 (files 0.png .. 9.png in Art/Fonts); WordLabel draws numbers from them and falls back to text while one is missing.")]
        public Sprite[] digits = new Sprite[10];

        static UISkin _current;
        static bool _loaded;

        /// <summary>The skin in Resources, or null when it has not been created yet (callers fall back to plain shapes).</summary>
        public static UISkin Current
        {
            get
            {
                if (!_loaded)
                {
                    _current = Resources.Load<UISkin>(ResourcePath);
                    _loaded = true;
                }
                return _current;
            }
        }
    }
}
